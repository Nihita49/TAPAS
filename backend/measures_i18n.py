def personal_multilang(band, city):
    """Return {lang: [messages]} for en + hi + the city's state language,
    aligned with measures.TIERS['user'][band] ordering."""
    from measures import measures_for
    en=measures_for(band,"user")
    sl=STATE_LANG.get(city,"hi")
    out={"en":en,"hi":[],"state":[]}
    hi=USER_I18N["hi"].get(band) or USER_I18N["hi"]["Severe"]
    st=USER_I18N[sl].get(band) or USER_I18N[sl]["Severe"]
    # align lengths to the English list (escalation may return a different band's list)
    out["hi"]=[hi[min(i,len(hi)-1)] for i in range(len(en))] if hi else [""]*len(en)
    out["state"]=[st[min(i,len(st)-1)] for i in range(len(en))] if st else [""]*len(en)
    out["state_lang"]=sl
    out["state_lang_name"]=LANG_NAME[sl]
    return out

def personal_oneline(band, city):
    """Compact trilingual first-line for SMS bodies."""
    from measures import measures_for
    en=measures_for(band,"user")
    m=personal_multilang(band, city)
    return " | ".join([en[0], "हिं: "+m["hi"][0], m["state_lang_name"]+": "+m["state"][0]])

